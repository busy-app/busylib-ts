// BusyBar class generator: src/BusyBar/scopes/*/functions.ts + BusyBar.template.ts  →  src/BusyBar/BusyBar.generated.ts
// Every exported function becomes a method with the same parameters minus `client`, the name with a capital letter and the same JSDoc minus `@param client`; the fixed part of the class comes from the template.
// Usage:
//   pnpm busybar:build   # generate
//   pnpm busybar:check   # verify it's up to date (CI)

import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as prettier from 'prettier';
import ts from 'typescript';

/** The package root: tools/busybar/ sits two levels under it. */
const root = fileURLToPath(new URL('../..', import.meta.url));
const scopesDir = resolve(root, 'src/BusyBar/scopes');
const templateFile = resolve(root, 'tools/busybar/BusyBar.template.ts');
const outFile = resolve(root, 'src/BusyBar/BusyBar.generated.ts');

const IMPORTS_MARKER = '// @busybar:imports';
const METHODS_MARKER = '// @busybar:methods';
const HEADER =
  '// Generated by tools/busybar/build-busybar.mjs from src/BusyBar/scopes/*/functions.ts and tools/busybar/BusyBar.template.ts. Do not edit by hand: change them and run `pnpm busybar:build`.';

/** Import specifier of a scope's functions, as written in BusyBar.generated.ts. */
const functionsModule = (scope) => `BusyBar/scopes/${scope}/functions`;

class ConventionError extends Error {}

function fail(file, node, message) {
  const { line } = node.getSourceFile().getLineAndCharacterOfPosition(node.getStart());
  throw new ConventionError(`${file}:${line + 1}: ${message}`);
}

/** Type names imported by the file, mapped to their module specifier. */
function typeImports(sourceFile, file) {
  const imports = new Map();

  for (const statement of sourceFile.statements) {
    if (!ts.isImportDeclaration(statement)) continue;

    const specifier = statement.moduleSpecifier.text;
    const bindings = statement.importClause?.namedBindings;
    if (!bindings || !ts.isNamedImports(bindings)) continue;

    for (const element of bindings.elements) {
      if (specifier.startsWith('.'))
        fail(file, statement, `import '${specifier}' with the BusyBar/... alias: BusyBar.generated.ts copies import specifiers as is`);
      imports.set(element.name.text, specifier);
    }
  }

  return imports;
}

/** Identifiers of all type references in a node: `Foo`, `Foo<Bar>`, `Foo['key']`. */
function referencedTypes(node, names = new Set()) {
  if (ts.isTypeReferenceNode(node)) {
    let name = node.typeName;
    while (ts.isQualifiedName(name)) name = name.left;
    names.add(name.text);
  }
  // forEachChild stops at the first truthy callback result, so the callback must not return the set.
  ts.forEachChild(node, (child) => {
    referencedTypes(child, names);
  });
  return names;
}

/** The function's JSDoc with the `@param client` line removed, as lines without the leading indentation. */
function methodDoc(fn, sourceFile, file) {
  const text = sourceFile.getFullText();
  const doc = (ts.getLeadingCommentRanges(text, fn.getFullStart()) ?? [])
    .map((range) => text.slice(range.pos, range.end))
    .findLast((comment) => comment.startsWith('/**'));
  if (!doc) fail(file, fn, `${fn.name.text}: JSDoc is required, BusyBar.generated.ts copies it`);

  const lines = doc.split('\n').map((line) => line.trim());
  const clientLine = lines.findIndex((line) => /^\* @param \{RequestClient\} client\b/.test(line));
  if (clientLine === -1) fail(file, fn, `${fn.name.text}: JSDoc must document the client as "@param {RequestClient} client"`);
  lines.splice(clientLine, 1);

  return lines.map((line) => (line.startsWith('*') ? ` ${line}` : line));
}

function readScope(scope) {
  const file = `src/BusyBar/scopes/${scope}/functions.ts`;
  const sourceFile = ts.createSourceFile(file, readFileSync(resolve(root, file), 'utf8'), ts.ScriptTarget.Latest, true);
  const imports = typeImports(sourceFile, file);
  const methods = [];

  for (const fn of sourceFile.statements) {
    if (!ts.isFunctionDeclaration(fn) || !fn.modifiers?.some((m) => m.kind === ts.SyntaxKind.ExportKeyword)) continue;

    const name = fn.name.text;
    if (!fn.modifiers.some((m) => m.kind === ts.SyntaxKind.AsyncKeyword))
      fail(file, fn, `${name}: must be async, so validation rejects the promise instead of throwing`);

    const [client, ...params] = fn.parameters;
    if (!client || client.name.getText() !== 'client' || client.type?.getText() !== 'RequestClient')
      fail(file, fn, `${name}: the first parameter must be "client: RequestClient"`);
    for (const param of params) {
      if (!ts.isIdentifier(param.name)) fail(file, param, `${name}: destructured parameters are not supported, take the object and destructure it in the body`);
    }

    const typeParams = fn.typeParameters ?? [];
    const ownTypes = new Set(typeParams.map((p) => p.name.text));
    const usedTypes = new Set();
    for (const node of [...typeParams, ...params]) {
      for (const type of referencedTypes(node)) if (!ownTypes.has(type)) usedTypes.add(type);
    }

    methods.push({
      scope,
      functionName: name,
      methodName: name[0].toUpperCase() + name.slice(1),
      doc: methodDoc(fn, sourceFile, file),
      typeParams: typeParams.map((p) => p.getText()),
      params: params.map((p) => p.getText()),
      args: params.map((p) => p.name.text),
      // Global types (Promise, Blob) are not imported anywhere and stay as they are.
      types: [...usedTypes].filter((type) => imports.has(type)).map((type) => [type, imports.get(type)])
    });
  }

  return methods;
}

/** The template without its header comment, with its type imports taken out to be merged with the generated ones. */
function readTemplate() {
  const file = 'tools/busybar/BusyBar.template.ts';
  const source = readFileSync(templateFile, 'utf8');
  const sourceFile = ts.createSourceFile(file, source, ts.ScriptTarget.Latest, true);

  for (const marker of [IMPORTS_MARKER, METHODS_MARKER]) {
    if (!source.includes(marker)) throw new ConventionError(`${file}: the "${marker}" marker is missing`);
  }

  const typeImports = sourceFile.statements.filter((s) => ts.isImportDeclaration(s) && s.importClause?.isTypeOnly);
  const types = new Map();
  for (const statement of typeImports) {
    const module = statement.moduleSpecifier.text;
    if (!types.has(module)) types.set(module, new Set());
    for (const element of statement.importClause.namedBindings.elements) types.get(module).add(element.name.text);
  }

  // Cut from the end, so earlier positions stay valid.
  let code = source;
  for (const statement of [...typeImports].reverse()) {
    code = code.slice(0, statement.getStart()) + code.slice(statement.getEnd()).replace(/^\n/, '');
  }

  return { types, code: code.slice(sourceFile.statements[0].getStart()) };
}

function renderImports(methods, templateTypes) {
  const typesByModule = new Map([...templateTypes].map(([module, names]) => [module, new Set(names)]));
  for (const { types } of methods) {
    for (const [type, module] of types) {
      if (!typesByModule.has(module)) typesByModule.set(module, new Set());
      typesByModule.get(module).add(type);
    }
  }

  const functionsByScope = new Map();
  for (const { scope, functionName } of methods) {
    if (!functionsByScope.has(scope)) functionsByScope.set(scope, []);
    functionsByScope.get(scope).push(functionName);
  }

  const functionImports = [...functionsByScope].map(([scope, names]) => `import { ${names.join(', ')} } from '${functionsModule(scope)}';`);
  const typeImportLines = [...typesByModule]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([module, names]) => `import type { ${[...names].sort().join(', ')} } from '${module}';`);

  return [...functionImports, ...typeImportLines].join('\n');
}

function renderMethod({ doc, methodName, functionName, typeParams, params, args }) {
  const generics = typeParams.length ? `<${typeParams.join(', ')}>` : '';
  const call = ['this.clientInstance', ...args].join(', ');
  return `${doc.join('\n')}\n${methodName}${generics}(${params.join(', ')}) {\n  return ${functionName}(${call});\n}`;
}

function render(methods, template) {
  const code = template.code
    .replace(IMPORTS_MARKER, () => renderImports(methods, template.types))
    .replace(METHODS_MARKER, () => methods.map(renderMethod).join('\n\n'));
  return `${HEADER}\n${code}`;
}

async function generate() {
  const scopes = existsSync(scopesDir) ? readdirSync(scopesDir).sort() : [];
  const methods = scopes.flatMap(readScope);

  const names = methods.map((m) => m.methodName);
  const duplicate = names.find((name, i) => names.indexOf(name) !== i);
  if (duplicate) throw new ConventionError(`${duplicate}: defined in more than one scope`);

  const config = await prettier.resolveConfig(outFile);
  return prettier.format(render(methods, readTemplate()), { ...config, filepath: outFile });
}

let output;
try {
  output = await generate();
} catch (error) {
  if (!(error instanceof ConventionError)) throw error;
  console.error(`busybar: ${error.message}`);
  process.exit(1);
}

if (process.argv.includes('--check')) {
  const current = existsSync(outFile) ? readFileSync(outFile, 'utf8') : '';
  if (current !== output) {
    console.error('busybar: src/BusyBar/BusyBar.generated.ts is out of date. Run `pnpm busybar:build`.');
    process.exit(1);
  }
  console.log('busybar: up to date');
  process.exit(0);
}

writeFileSync(outFile, output);
console.log(`busybar: ${outFile.slice(root.length)}`);
